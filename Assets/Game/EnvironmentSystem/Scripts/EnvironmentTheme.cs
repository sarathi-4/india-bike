namespace IndianBikeLife.EnvironmentSystem
{
    /// <summary>
    /// Distinct Indian regional environmental themes governing building styles, vegetation, and prop placement.
    /// </summary>
    public enum EnvironmentTheme
    {
        VillageRural = 0,        // Thatched huts, cattle sheds, banyan/neem trees, dirt shoulders
        TownCommercial = 1,      // 2-story brick shopfronts, tea stalls, bus shelters, autorickshaw stands
        CityMetropolitan = 2,    // Concrete apartments, flyovers, traffic signals, modern hoardings
        HighwayCorridor = 3,     // Dhabas, petrol pumps, toll plazas, kilometer stones, streetlights
        HillStationGhat = 4,     // Tea estates, pine/eucalyptus trees, hairpin crash barriers, misty cliffs
        CoastalBeach = 5         // Coconut palms, fishing boats, coastal highway barriers, sand banks
    }
}
