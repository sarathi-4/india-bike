namespace IndianBikeLife.RidingModes
{
    /// <summary>
    /// The ten distinct motorcycle riding experiences of Indian Bike Life.
    /// </summary>
    public enum RidingModeType
    {
        VillageRide = 0,        // Narrow village roads, huts, slow traffic
        CityRide = 1,           // Dense urban intersections, auto-rickshaws, traffic lights
        HighwayRide = 2,        // High-speed national highways, dhabas, heavy trucks
        HillStationGhatRide = 3,// Curved mountain roads, hairpin bends, misty valleys
        LongDistanceTrip = 4,   // Multi-city highway tour with checkpoints
        FreeRide = 5,           // Open unconstrained exploration
        OffRoadRide = 6,        // Dirt trails, gravel, rugged terrain
        NightRide = 7,          // Midnight highways, dark winding roads, headlights
        RaceTrackRide = 8,      // Enclosed circuit track, lap timer foundations
        CoupleRide = 9          // Romantic scenic ride with passenger integration
    }
}
